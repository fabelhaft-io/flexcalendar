import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { download, ensureToolchains, verified } from './lib/toolchains.js';

// `make host-tools`: puts the pinned PHP, Composer, Flutter and Dart on the dev host's PATH as
// shims, without root and without containers, so `make verify`, `make gen` and the reviewer's
// stack checks run on the host. The host has none of them (.agents/skills/orchestrate/environment.md).
//
// PHP and Composer are the sandbox's own pinned build (src/lib/toolchains.ts), so there is one
// pin and one set of hashes. Flutter's version is the one in apps/mobile/.fvmrc and its SHA-256
// comes from Google's release metadata; Dart is the one inside that Flutter. Shims are written
// to --bin-dir (default ~/.local/bin) and only over files this script wrote.

const REPO_ROOT = path.resolve(import.meta.dirname, '..', '..');
const MARKER = '# calendar-flex host-tools shim: generated by `make host-tools`, do not edit.';
const RELEASES_URL = 'https://storage.googleapis.com/flutter_infra_release/releases/releases_linux.json';
const RELEASES_BASE = 'https://storage.googleapis.com/flutter_infra_release/releases/';
const DOWNLOAD_TIMEOUT_MS = 30 * 60 * 1000;

const { values } = parseArgs({
  options: {
    'bin-dir': { type: 'string', default: path.join(os.homedir(), '.local', 'bin') },
    'skip-flutter': { type: 'boolean', default: false },
  },
});
const binDir = path.resolve(values['bin-dir']);
const toolsRoot = path.join(os.homedir(), '.cache', 'calendar-flex-host-tools');

function q(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

function pinnedFlutterVersion(): string {
  const pin: unknown = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'apps/mobile/.fvmrc'), 'utf8'));
  const version = typeof pin === 'object' && pin !== null ? (pin as { flutter?: unknown }).flutter : undefined;
  if (typeof version !== 'string' || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error('apps/mobile/.fvmrc has no exact "flutter" version');
  }
  return version;
}

interface FlutterRelease {
  version: string;
  channel: string;
  archive: string;
  sha256: string;
}

function flutterRelease(version: string, staging: string): FlutterRelease {
  const file = path.join(staging, 'releases_linux.json');
  download(RELEASES_URL, file);
  const parsed: unknown = JSON.parse(fs.readFileSync(file, 'utf8'));
  const releases = (parsed as { releases?: FlutterRelease[] }).releases ?? [];
  const release = releases.find((r) => r.version === version && r.channel === 'stable');
  if (!release) throw new Error(`Flutter ${version} is not a stable release in ${RELEASES_URL}`);
  return release;
}

/** Downloads, verifies and unpacks the pinned Flutter once; returns its directory. */
function ensureFlutter(version: string): string {
  const target = path.join(toolsRoot, `flutter-${version}`);
  if (fs.existsSync(path.join(target, 'bin', 'flutter'))) return target;
  fs.mkdirSync(toolsRoot, { recursive: true });
  const staging = fs.mkdtempSync(path.join(toolsRoot, '.staging-'));
  try {
    const release = flutterRelease(version, staging);
    const archive = path.join(staging, 'flutter.tar.xz');
    console.log(`Downloading Flutter ${version} (over a gigabyte; this takes a few minutes)...`);
    download(RELEASES_BASE + release.archive, archive, DOWNLOAD_TIMEOUT_MS);
    verified(archive, release.sha256, `Flutter ${version} archive`);
    const tar = spawnSync('tar', ['-xJf', archive, '-C', staging], { encoding: 'utf8' });
    if (tar.error || tar.status !== 0) throw new Error(`unpacking Flutter failed: ${tar.error?.message ?? tar.stderr.trim()}`);
    fs.rmSync(target, { recursive: true, force: true });
    fs.renameSync(path.join(staging, 'flutter'), target);
  } finally {
    fs.rmSync(staging, { recursive: true, force: true });
  }
  return target;
}

function flutterShim(flutterDir: string, tool: 'flutter' | 'dart'): string {
  // A private HOME and pub cache keep the tools' state out of the owner's home. Gradle and the
  // Android SDK stay the real ones, or a build would fetch Gradle and the SDK again.
  return `#!/bin/sh
${MARKER}
REAL_HOME="$HOME"
export HOME=${q(path.join(toolsRoot, 'home'))} PUB_CACHE=${q(path.join(toolsRoot, 'pub-cache'))}
export GRADLE_USER_HOME="\${GRADLE_USER_HOME:-$REAL_HOME/.gradle}"
[ -d "$REAL_HOME/Android/Sdk" ] && export ANDROID_HOME="\${ANDROID_HOME:-$REAL_HOME/Android/Sdk}"
export FLUTTER_SUPPRESS_ANALYTICS=true DART_SUPPRESS_ANALYTICS=true CI=true
exec ${q(path.join(flutterDir, 'bin', tool))} "$@"
`;
}

// The static PHP build has no php.ini, and the 128M default memory limit crashes PHPStan's
// parallel workers (found by running `make verify-server-caldav` on the host). PHPRC is
// inherited by the processes PHPStan and Composer start, which a `-d` option would not be.
const PHP_INI = '; Written by `make host-tools`.\nmemory_limit = -1\n';

function phpShim(target: string): string {
  return `#!/bin/sh\n${MARKER}\nexport PHPRC=${q(path.join(toolsRoot, 'php'))}\nexec ${q(target)} "$@"\n`;
}

const skipped = new Set<string>();

/** Writes one shim, but never over a file this script did not write. */
function writeShim(name: string, content: string): void {
  const file = path.join(binDir, name);
  const stat = fs.lstatSync(file, { throwIfNoEntry: false });
  if (stat) {
    const existing = stat.isFile() ? fs.readFileSync(file, 'utf8') : '';
    if (!existing.includes(MARKER)) {
      console.warn(`skipped ${file}: it exists and is not a host-tools shim; remove it to use the pinned ${name}`);
      skipped.add(name);
      return;
    }
    if (existing === content) return;
  }
  fs.mkdirSync(binDir, { recursive: true });
  fs.writeFileSync(file, content, { mode: 0o755 });
  console.log(`wrote ${file}`);
}

/** Runs a shim and prints its first output line. A skipped shim is not ours, so it is not run. */
function report(name: string, args: string[]): boolean {
  if (skipped.has(name)) {
    console.log(`FAIL ${name}: not installed, an existing file was left alone`);
    return false;
  }
  const r = spawnSync(path.join(binDir, name), args, { encoding: 'utf8', timeout: 15 * 60 * 1000 });
  const first = (r.error?.message ?? `${r.stdout ?? ''}${r.stderr ?? ''}`).trim().split('\n')[0] ?? '';
  console.log(`${r.status === 0 ? 'ok  ' : 'FAIL'} ${name}: ${first}`);
  return r.status === 0;
}

function main(): number {
  const tools = ensureToolchains();
  if (!tools) {
    console.error('PHP and Composer could not be provisioned (see the warning above).');
    return 1;
  }
  fs.mkdirSync(path.join(toolsRoot, 'php'), { recursive: true });
  fs.writeFileSync(path.join(toolsRoot, 'php', 'php.ini'), PHP_INI);
  writeShim('php', phpShim(tools.php));
  writeShim('composer', phpShim(tools.composer));

  if (!values['skip-flutter']) {
    const flutterDir = ensureFlutter(pinnedFlutterVersion());
    writeShim('flutter', flutterShim(flutterDir, 'flutter'));
    writeShim('dart', flutterShim(flutterDir, 'dart'));
  }

  if (!(process.env.PATH ?? '').split(path.delimiter).includes(binDir)) {
    console.warn(`${binDir} is not on PATH; add it so \`php\`, \`composer\`, \`flutter\` and \`dart\` resolve.`);
  }

  // Every tool is reported, so no failure hides behind an earlier one.
  const results = [report('php', ['-v']), report('composer', ['--version'])];
  if (!skipped.has('php')) {
    const modules = spawnSync(path.join(binDir, 'php'), ['-m'], { encoding: 'utf8' }).stdout ?? '';
    if (!/^pdo_pgsql$/m.test(modules)) {
      console.error("FAIL php: the extension pdo_pgsql is missing, so Composer's platform check would fail");
      results.push(false);
    }
  }
  if (!values['skip-flutter']) {
    results.push(report('flutter', ['--version']), report('dart', ['--version']));
  }
  return results.every(Boolean) ? 0 : 1;
}

process.exit(main());
